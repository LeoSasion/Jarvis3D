const OFFLINE_GLYPH_PLACEHOLDER = "□";
const EMPTY_LABEL = "Untitled";
let decodedGlyphBitmap;

function getGlyphBitmap() {
  if (!decodedGlyphBitmap) {
    decodedGlyphBitmap = Uint8Array.from(atob(GRAPH_LABEL_GLYPH_BITMAP), (character) =>
      character.charCodeAt(0),
    );
  }
  return decodedGlyphBitmap;
}

function supportsOfflineGlyph(codePoint, bitmap) {
  return (
    codePoint <= 0xffff &&
    (bitmap[codePoint >>> 3] & (1 << (codePoint & 7))) !== 0
  );
}

export function formatGraphLabelText(value) {
  const bitmap = getGlyphBitmap();
  const formatted = Array.from(String(value ?? ""), (character) => {
    if (/\s/u.test(character)) return " ";
    return supportsOfflineGlyph(character.codePointAt(0), bitmap)
      ? character
      : OFFLINE_GLYPH_PLACEHOLDER;
  })
    .join("")
    .replace(/\s+/g, " ")
    .trim();
  return formatted || EMPTY_LABEL;
}
